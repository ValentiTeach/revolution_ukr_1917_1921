# Скільки рядків опускаються під базову лінію (Д, Ц, Щ) або піднімаються над великою (Ї, Й, Ґ)
_TINY_BELOW = {'Д': 1, 'Ц': 1, 'Щ': 1, ',': 1}

TINY: dict[str, tuple[list[str], int]] = {k: (v, _TINY_BELOW.get(k, 0)) for k, v in _TINY_SRC.items()}
BIG: dict[str, tuple[list[str], int]] = _parse_big()


def measure(s: str, font: str = 'tiny') -> int:
    f = TINY if font == 'tiny' else BIG
    s = s.upper() if font == 'tiny' else s
    w = 0
    for ch in s:
        if ch in f:
            w += len(f[ch][0][0]) + 1
        else:
            w += 4 if font == 'tiny' else 6
    return max(0, w - 1)


def draw_text(cv, x: int, base: int, s: str, color: Color, font: str = 'tiny', shadow: Color | None = None, outline: Color | None = None) -> int:
    """Пише рядок; base — базова лінія (низ великих літер). Повертає ширину."""
    f = TINY if font == 'tiny' else BIG
    s = s.upper() if font == 'tiny' else s

    def put(px: int, py: int, c: Color) -> None:
        cv.set(px, py, c)

    cx = x
    pixels: list[tuple[int, int]] = []
    for ch in s:
        if ch not in f:
            cx += 4 if font == 'tiny' else 6
            continue
        rows, below = f[ch]
        above = len(rows) - below
        top = base - above
        for ry, row in enumerate(rows):
            for rx, c in enumerate(row):
                if c == '#':
                    pixels.append((cx + rx, top + ry))
        cx += len(rows[0]) + 1
    if outline:
        ps = set(pixels)
        for (px, py) in pixels:
            for dx in (-1, 0, 1):
                for dy in (-1, 0, 1):
                    if (px + dx, py + dy) not in ps:
                        put(px + dx, py + dy, outline)
    if shadow:
        ps = set(pixels)
        for (px, py) in pixels:
            if (px + 1, py + 1) not in ps:
                put(px + 1, py + 1, shadow)
    for (px, py) in pixels:
        put(px, py, color)
    return cx - x - 1


def draw_centered(cv, cx: int, base: int, s: str, color: Color, font: str = 'tiny', **kw) -> None:
    draw_text(cv, cx - measure(s, font) // 2, base, s, color, font, **kw)
