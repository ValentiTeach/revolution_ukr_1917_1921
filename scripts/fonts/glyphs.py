# Гліфи, що збігаються з уже намальованими
ALIASES = {
    'А': 'A', 'В': 'B', 'Е': 'E', 'І': 'I', 'К': 'K', 'М': 'M', 'Н': 'H', 'О': 'O',
    'Р': 'P', 'С': 'C', 'Т': 'T', 'Х': 'X',
    'а': 'a', 'е': 'e', 'і': 'i', 'о': 'o', 'р': 'p', 'с': 'c', 'у': 'y', 'х': 'x',
    ' ': ' ', ' ': ' ', ' ': ' ', '‑': '-', '‐': '-',
    '´': "'", '′': "'",
}


def parse() -> dict[str, tuple[list[str], int]]:
    """Повертає {символ: (рядки зверху вниз, кількість рядків під базовою лінією)}."""
    out: dict[str, tuple[list[str], int]] = {}
    blocks = [b for b in GLYPHS.strip('\n').split('\n\n') if b.strip()]
    for block in blocks:
        lines = block.split('\n')
        key = lines[0]
        ch = chr(int(key[2:], 16)) if key.startswith('U+') and len(key) > 2 else key
        rows: list[str] = []
        below = 0
        seen_tilde = False
        for ln in lines[1:]:
            if ln == '~' and not seen_tilde:
                seen_tilde = True
                continue
            rows.append(ln)
            if seen_tilde:
                below += 1
        if ch in out:
            raise ValueError(f'Гліф {ch!r} описано двічі')
        width = max(len(r) for r in rows)
        out[ch] = ([r.ljust(width, '.') for r in rows], below)
    for a, src in ALIASES.items():
        out[a] = out[src]
    return out
